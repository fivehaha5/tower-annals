export const SKILL_MAP = Object.fromEntries(SKILLS.map((s) => [s.id, s])) as Record<string, SkillDef>

export function defaultSkills(role: Role): Record<SkillKind, string> {
  if (role === 'warrior') return { attack: 'w_atk', defense: 'w_def', support: 'w_sup' }
  if (role === 'mage') return { attack: 'm_atk', defense: 'm_def', support: 'm_sup' }
  return { attack: 'p_atk', defense: 'p_def', support: 'p_sup' }
}

export function uniqueSkillsBySource(source: 'boss' | 'godking'): SkillDef[] {
  return SKILLS.filter((s) => s.unique && s.source === source)
}

/** 克制王階技能池（非王塔／神王掉落） */
export function antiKingSkills(): SkillDef[] {
  return SKILLS.filter((s) => s.source === 'antiKing')
}

export const SHOP_SKILL_RARITIES: Rarity[] = ['普通', '稀有']

export function shopSkillCatalog(): { def: SkillDef; rarity: Rarity }[] {
  const basics = SKILLS.filter((s) => !s.unique)
  const out: { def: SkillDef; rarity: Rarity }[] = []
  for (const def of basics) {
    for (const rarity of SHOP_SKILL_RARITIES) out.push({ def, rarity })
  }
  return out
}

export function dropSkillRarity(def: SkillDef): Rarity {
  if (def.source === 'godking') return '永恆'
  if (def.source === 'boss') return '神話'
  if (def.source === 'antiKing') return '史詩'
  return '史詩'
}
